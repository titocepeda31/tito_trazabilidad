CREATE TABLE IF NOT EXISTS maderas7_ttrazabilidad.quote_followups (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 business_id BIGINT UNSIGNED NOT NULL,
 quote_id BIGINT UNSIGNED NOT NULL,
 client_id BIGINT UNSIGNED NOT NULL,
 kind ENUM('contact','task') NOT NULL,
 channel ENUM('phone','email','whatsapp','meeting','other') NOT NULL,
 note VARCHAR(1000) NOT NULL,
 due_on DATE NULL,
 assigned_to BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status ENUM('recorded','pending','done','cancelled') NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 closed_by BIGINT UNSIGNED NULL,
 closed_at DATETIME NULL,
 close_note VARCHAR(500) NULL,
 close_request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 close_payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 UNIQUE KEY uq_followup_request(business_id,request_id),
 UNIQUE KEY uq_followup_close(business_id,close_request_id),
 KEY idx_followup_quote(business_id,quote_id,id),
 KEY idx_followup_client(business_id,client_id,id),
 KEY idx_followup_due(business_id,status,due_on,id),
 CONSTRAINT fk_followup_quote FOREIGN KEY(quote_id) REFERENCES maderas7_ttrazabilidad.quotes(id),
 CONSTRAINT fk_followup_client FOREIGN KEY(client_id) REFERENCES maderas7_ttrazabilidad.habitual_clients(id),
 CONSTRAINT fk_followup_assignee FOREIGN KEY(assigned_to) REFERENCES maderas7_ttrazabilidad.users(id),
 CONSTRAINT fk_followup_creator FOREIGN KEY(created_by) REFERENCES maderas7_ttrazabilidad.users(id),
 CONSTRAINT fk_followup_closer FOREIGN KEY(closed_by) REFERENCES maderas7_ttrazabilidad.users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
