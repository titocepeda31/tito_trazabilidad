CREATE TABLE IF NOT EXISTS maderas7_ttrazabilidad.warranty_policies (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 business_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NULL,
 kind ENUM('satisfaction','manufacturer') NOT NULL,
 offered TINYINT UNSIGNED NOT NULL DEFAULT 1,
 duration_value SMALLINT UNSIGNED NULL,
 duration_unit ENUM('days','months','years') NULL,
 start_event ENUM('sale','receipt','installation') NOT NULL,
 requires_notification TINYINT UNSIGNED NOT NULL DEFAULT 0,
 terms VARCHAR(1000) NOT NULL,
 evidence_reference VARCHAR(250) NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_warranty_policy_request(business_id,request_id),
 KEY idx_warranty_policy_scope(business_id,kind,product_id,id),
 CONSTRAINT fk_warranty_policy_product FOREIGN KEY(product_id) REFERENCES maderas7_ttrazabilidad.products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS maderas7_ttrazabilidad.sale_warranty_coverages (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 business_id BIGINT UNSIGNED NOT NULL,
 sale_id BIGINT UNSIGNED NOT NULL,
 sale_item_id BIGINT UNSIGNED NOT NULL,
 unit_id BIGINT UNSIGNED NULL,
 unit_key BIGINT UNSIGNED NOT NULL DEFAULT 0,
 client_id BIGINT UNSIGNED NULL,
 kind ENUM('legal','satisfaction','manufacturer') NOT NULL,
 policy_id BIGINT UNSIGNED NULL,
 offered TINYINT UNSIGNED NULL,
 duration_value SMALLINT UNSIGNED NULL,
 duration_unit ENUM('days','months','years') NULL,
 start_event ENUM('sale','receipt','installation') NOT NULL,
 starts_on DATE NULL,
 ends_on DATE NULL,
 terms VARCHAR(1000) NOT NULL,
 manufacturer_name VARCHAR(150) NULL,
 activation_status ENUM('unknown','not_required','pending','reported','confirmed','observed') NOT NULL DEFAULT 'unknown',
 notified_on DATE NULL,
 confirmed_on DATE NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_sale_warranty_line(sale_item_id,unit_key,kind),
 KEY idx_sale_warranty_business(business_id,kind,activation_status,id),
 KEY idx_sale_warranty_client(business_id,client_id,id),
 CONSTRAINT fk_sale_warranty_sale FOREIGN KEY(sale_id) REFERENCES maderas7_ttrazabilidad.sales(id),
 CONSTRAINT fk_sale_warranty_line FOREIGN KEY(sale_item_id) REFERENCES maderas7_ttrazabilidad.sale_items(id),
 CONSTRAINT fk_sale_warranty_unit FOREIGN KEY(unit_id) REFERENCES maderas7_ttrazabilidad.serial_units(id),
 CONSTRAINT fk_sale_warranty_policy FOREIGN KEY(policy_id) REFERENCES maderas7_ttrazabilidad.warranty_policies(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS maderas7_ttrazabilidad.warranty_coverage_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 business_id BIGINT UNSIGNED NOT NULL,
 coverage_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 kind ENUM('base_date','reported','confirmed','observed','note','policy') NOT NULL,
 note VARCHAR(1000) NOT NULL,
 evidence_reference VARCHAR(250) NOT NULL,
 event_on DATE NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_warranty_event_request(business_id,request_id),
 KEY idx_warranty_event_coverage(business_id,coverage_id,id),
 CONSTRAINT fk_warranty_event_coverage FOREIGN KEY(coverage_id) REFERENCES maderas7_ttrazabilidad.sale_warranty_coverages(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
